export async function syncOfficialCatalogToFirestore(): Promise<{
  productCount: number;
  packageCount: number;
}> {
  try {
    let productCount = 0;
    let packageCount = 0;

    for (const oldId of OLD_DEMO_PRODUCT_IDS) {
      const oldRef = doc(db, 'products', oldId);
      const oldSnap = await getDoc(oldRef);
      if (oldSnap.exists()) {
        await deleteDoc(oldRef);
      }
    }

    for (const oldPkgId of OLD_DEMO_PACKAGE_IDS) {
      const oldPkgRef = doc(db, 'packages', oldPkgId);
      const oldPkgSnap = await getDoc(oldPkgRef);
      if (oldPkgSnap.exists()) {
        await deleteDoc(oldPkgRef);
      }
    }

    await Promise.all([
      ...OFFNOT_PRODUCTS.map(async (prod) => {
        const prodRef = doc(db, 'products', prod.id);
        const prodSnap = await getDoc(prodRef);
        await setDoc(
          prodRef,
          buildCleanProductWrite(prod, prodSnap.exists() ? prodSnap.data()?.createdAt : undefined)
        );
        productCount++;
      }),
      ...OFFNOT_PACKAGES.map(async (pkg) => {
        const pkgRef = doc(db, 'packages', pkg.id);
        const pkgSnap = await getDoc(pkgRef);
        await setDoc(
          pkgRef,
          buildCleanPackageWrite(pkg, pkgSnap.exists() ? pkgSnap.data()?.createdAt : undefined)
        );
        packageCount++;
      }),
    ]);

    return { productCount, packageCount };
  } catch (err) {
    handleFirestoreError(err, OperationType.WRITE, 'syncOfficialCatalog');
  }
}

export async function seedInitialCatalogIfAdmin(): Promise<{
  productCount: number;
  packageCount: number;
}> {
  try {
    const configRef = doc(db, 'settings', 'storeConfig');
    const configSnap = await getDoc(configRef);
    if (!configSnap.exists()) {
      await setDoc(configRef, {
        ...DEFAULT_STORE_SETTINGS,
        updatedAt: serverTimestamp(),
      });
    }

    const synced = await syncOfficialCatalogToFirestore();

    for (const [role, perms] of Object.entries(DEFAULT_ROLE_PERMISSIONS)) {
      const roleRef = doc(db, 'rolePermissions', role);
      const roleSnap = await getDoc(roleRef);
      if (!roleSnap.exists()) {
        await setDoc(roleRef, {
          ...perms,
          updatedAt: serverTimestamp(),
        });
      }
    }

    return synced;
  } catch (err) {
    handleFirestoreError(err, OperationType.WRITE, 'seedInitialCatalog');
  }
}
